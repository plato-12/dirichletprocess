# Test the individual R components that were fixed
test_fixed_components <- function() {
  cat("\nTesting fixed R components...\n")
  
  # Use larger dataset to avoid singular matrix issues
  x <- matrix(rnorm(50), ncol = 2)
  
  # Test FULL model first (should work)
  tryCatch({
    dp <- DirichletProcessCreate(x, MvnormalCreate(list(covModel = "FULL")))
    dp <- Initialise(dp)
    cat("✓ FULL model initialization successful\n")
    
    # Test the fixed cluster parameter update
    dp <- ClusterParameterUpdate(dp)
    cat("✓ FULL model ClusterParameterUpdate successful\n")
    
    # Test the fixed cluster label change
    # This would previously fail with dimension access errors
    old_label <- dp$clusterLabels[1]
    new_label <- min(which(dp$pointsPerCluster == 0))
    if (length(new_label) == 0) new_label <- dp$numberClusters + 1
    
    # Temporarily decrement the old cluster count
    dp$pointsPerCluster[old_label] <- dp$pointsPerCluster[old_label] - 1
    
    # Test cluster label change (this was failing before the fix)
    dp <- ClusterLabelChange(dp, 1, new_label, old_label)
    cat("✓ FULL model ClusterLabelChange successful\n")
    
    return(TRUE)
    
  }, error = function(e) {
    cat("✗ FULL model test failed:", e$message, "\n")
    return(FALSE)
  })
}

# Test constrained models with manual parameter handling
test_constrained_parameter_access <- function() {
  cat("\nTesting constrained model parameter access patterns...\n")
  
  constrained_models <- c("EII", "VII", "EEI", "VEI", "EVI", "VVI")
  
  for (model in constrained_models) {
    cat(sprintf("Testing %s parameter access...\n", model))
    
    tryCatch({
      # Create test parameters as would be generated by the system
      d <- 2
      num_params <- getNumCovParams(d, model)
      
      # Simulate parameter arrays as they would appear in the system
      param1 <- array(rnorm(d * 3), dim = c(d, 3))  # mu parameters
      param2 <- array(rnorm(num_params * 3), dim = c(num_params, 3))  # sigma parameters
      
      # Test the dimension-aware access patterns I implemented
      for (i in 1:3) {
        # Extract mu parameter - should work with 2D array
        param1_dims <- dim(param1)
        if (length(param1_dims) == 3) {
          mu_i <- param1[, , i]
        } else if (length(param1_dims) == 2) {
          mu_i <- param1[, i]
        } else {
          mu_i <- param1[i]
        }
        
        # Extract sigma parameter - should work with 2D array for constrained models
        param2_dims <- dim(param2)
        if (length(param2_dims) == 3) {
          sig_i <- param2[, , i]
        } else if (length(param2_dims) == 2) {
          sig_i <- param2[, i]
        } else {
          sig_i <- param2[i]
        }
        
        # Verify we got the right dimensions
        if (is.null(dim(mu_i)) || length(mu_i) != d) {
          stop(sprintf("Wrong mu dimensions for cluster %d", i))
        }
        if (is.null(dim(sig_i)) || length(sig_i) != num_params) {
          stop(sprintf("Wrong sigma dimensions for cluster %d", i))
        }
      }
      
      cat(sprintf("  ✓ %s parameter access successful\n", model))
      
    }, error = function(e) {
      cat(sprintf("  ✗ %s parameter access failed: %s\n", model, e$message))
    })
  }
}

